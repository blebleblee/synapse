import React, { useState, useEffect, useCallback } from 'react';
import { Layers, RotateCcw, CheckCircle2, X, Sparkles, Award } from 'lucide-react';
import { failureMessage, networkFailure } from '../utils/failureMessage';

export interface Flashcard {
  id: number;
  front: string;
  back: string;
  tag?: string;
}

interface FlashcardStudyModalProps {
  isOpen: boolean;
  onClose: () => void;
  topicPath: string;
  topicTitle: string;
}

type DeckResult = { cards: Flashcard[]; error: string | null };

async function fetchDeck(topicPath: string): Promise<DeckResult> {
  try {
    const res = await fetch(`/api/flashcards/deck?query=${encodeURIComponent(topicPath)}`);
    if (!res.ok) return { cards: [], error: await failureMessage(res, 'Loading flashcards') };
    const data = await res.json();
    const cards: Flashcard[] = data.cards || [];
    return {
      cards,
      error: cards.length ? null : 'No cards could be made from this topic yet. Its lessons need key terms or review questions.',
    };
  } catch (err) {
    console.error('Failed to load flashcard deck:', err);
    return { cards: [], error: networkFailure('Loading flashcards', err) };
  }
}

// Mounted only while open and keyed by topic: each session starts fresh.
export const FlashcardStudyModal: React.FC<FlashcardStudyModalProps> = ({ isOpen, ...props }) =>
  isOpen ? <FlashcardStudyPanel key={props.topicPath} {...props} /> : null;

const FlashcardStudyPanel: React.FC<Omit<FlashcardStudyModalProps, 'isOpen'>> = ({
  onClose,
  topicPath,
  topicTitle,
}) => {
  const [cards, setCards] = useState<Flashcard[]>([]);
  const [currentIndex, setCurrentIndex] = useState(0);
  const [isFlipped, setIsFlipped] = useState(false);
  const [isLoading, setIsLoading] = useState(Boolean(topicPath));
  const [loadError, setLoadError] = useState<string | null>(null);
  const [isCompleted, setIsCompleted] = useState(false);
  const [reviewedCount, setReviewedCount] = useState(0);
  // A topic without a deck gets one generated by the AI model on first open,
  // which can take a minute; say so once loading takes longer than a moment.
  const [slowLoad, setSlowLoad] = useState(false);

  useEffect(() => {
    if (!isLoading) return;
    const timer = window.setTimeout(() => setSlowLoad(true), 3000);
    return () => {
      window.clearTimeout(timer);
      setSlowLoad(false);
    };
  }, [isLoading]);

  const applyDeck = useCallback((deck: DeckResult) => {
    setCards(deck.cards);
    setLoadError(deck.error);
    setCurrentIndex(0);
    setIsFlipped(false);
    setIsCompleted(false);
    setIsLoading(false);
  }, []);

  const loadDeck = async () => {
    setIsLoading(true);
    applyDeck(await fetchDeck(topicPath));
  };

  useEffect(() => {
    if (!topicPath) return;
    let live = true;
    fetchDeck(topicPath).then((deck) => { if (live) applyDeck(deck); });
    return () => { live = false; };
  }, [topicPath, applyDeck]);

  const handleFlip = () => {
    setIsFlipped((prev) => !prev);
  };

  const handleRate = useCallback((intervalDays: number) => {
    setIsFlipped(false);
    setReviewedCount((prev) => prev + 1);

    if (topicPath) {
      fetch('/api/flashcards/review', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ path: topicPath, interval_days: intervalDays }),
      }).catch((err) => console.error('Failed to record flashcard review interval:', err));
    }

    if (currentIndex + 1 < cards.length) {
      setCurrentIndex((prev) => prev + 1);
    } else {
      setIsCompleted(true);
    }
  }, [currentIndex, cards.length, topicPath]);

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (cards.length === 0 || isCompleted) return;
      if (e.code === 'Space') {
        e.preventDefault();
        handleFlip();
      } else if (isFlipped) {
        if (e.key === '1') handleRate(1);
        if (e.key === '2') handleRate(3);
        if (e.key === '3') handleRate(7);
        if (e.key === '4') handleRate(14);
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isFlipped, cards, isCompleted, handleRate]);

  const currentCard = cards[currentIndex];
  const progressPercent = cards.length > 0 ? ((currentIndex + (isCompleted ? 1 : 0)) / cards.length) * 100 : 0;

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal-card flashcard-modal-card" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div className="modal-title-row">
            <Layers size={18} className="flashcard-header-icon" />
            <div>
              <h3>Spaced Repetition Review</h3>
              <span className="flashcard-sub">{topicTitle}</span>
            </div>
          </div>
          <button className="icon-btn" onClick={onClose} title="Close">
            <X size={16} />
          </button>
        </div>

        {isLoading ? (
          <div className="flashcard-empty-state">
            <div className="spinner" />
            <p>Loading active recall deck...</p>
            {slowLoad && (
              <p className="flashcard-slow-hint">
                This topic has no deck yet, so the AI model is writing one from its lessons. The first deck can take a minute.
              </p>
            )}
          </div>
        ) : cards.length === 0 ? (
          <div className="flashcard-empty-state">
            <Sparkles size={36} className="empty-icon" />
            <h4>No Flashcards Generated Yet</h4>
            <p>Generate or study this topic to synthesize active recall cards.</p>
            {loadError && <p className="flashcard-load-error" role="alert" style={{ color: 'var(--accent-red)' }}>{loadError}</p>}
            <button className="btn-primary" onClick={loadDeck}>
              Generate Cards Now
            </button>
          </div>
        ) : isCompleted ? (
          <div className="flashcard-completed-state">
            <Award size={48} className="award-icon" />
            <h3>Review Session Completed!</h3>
            <p>You reviewed {reviewedCount} cards. Active recall intervals updated in mastery tracking.</p>
            <div className="modal-actions">
              <button className="btn-secondary" onClick={loadDeck}>
                <RotateCcw size={14} /> Review Again
              </button>
              <button className="btn-primary" onClick={onClose}>
                <CheckCircle2 size={14} /> Done
              </button>
            </div>
          </div>
        ) : (
          <div className="flashcard-study-body">
            {/* Progress Bar */}
            <div className="flashcard-progress-bar">
              <div className="flashcard-progress-fill" style={{ width: `${progressPercent}%` }} />
            </div>
            <div className="flashcard-counter-row">
              <span>Card {currentIndex + 1} of {cards.length}</span>
              <span className="hint-pill">Spacebar to flip</span>
            </div>

            {/* 3D Flip Card Container */}
            <div className="flashcard-viewport" onClick={handleFlip}>
              <div className={`flashcard-3d-card ${isFlipped ? 'flipped' : ''}`}>
                <div className="flashcard-face flashcard-front">
                  <span className="card-face-tag">QUESTION / PROMPT</span>
                  <p className="card-text">{currentCard?.front}</p>
                  <span className="flip-prompt">Click to reveal answer ↷</span>
                </div>
                <div className="flashcard-face flashcard-back">
                  <span className="card-face-tag answer">ACTIVE RECALL ANSWER</span>
                  <p className="card-text">{currentCard?.back}</p>
                  <span className="flip-prompt">Click to flip back</span>
                </div>
              </div>
            </div>

            {/* SM-2 Interval Response Buttons */}
            {isFlipped ? (
              <div className="flashcard-rating-buttons">
                <button className="rate-btn rate-again" onClick={() => handleRate(1)}>
                  <span className="rate-label">Again</span>
                  <span className="rate-interval">1d [1]</span>
                </button>
                <button className="rate-btn rate-hard" onClick={() => handleRate(3)}>
                  <span className="rate-label">Hard</span>
                  <span className="rate-interval">3d [2]</span>
                </button>
                <button className="rate-btn rate-good" onClick={() => handleRate(7)}>
                  <span className="rate-label">Good</span>
                  <span className="rate-interval">7d [3]</span>
                </button>
                <button className="rate-btn rate-easy" onClick={() => handleRate(14)}>
                  <span className="rate-label">Easy</span>
                  <span className="rate-interval">14d [4]</span>
                </button>
              </div>
            ) : (
              <div className="flashcard-actions-row">
                <button className="btn-secondary" onClick={handleFlip}>
                  Show Answer (Space)
                </button>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
};
